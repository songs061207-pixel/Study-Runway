function buildLearningItemFromPreset(
  preset: LearningResourcePreset,
  now: Date,
): LearningItem {
  const nowIso = now.toISOString();
  const deadline = getDateKey(addDays(now, preset.deadlineOffsetDays));

  return normalizeLearningItems([
    {
      id: preset.id,
      title: preset.title,
      type: preset.type,
      intensity: preset.intensity,
      deadline,
      priority: preset.priority,
      estimatedMinutes: preset.estimatedMinutes,
      progressMinutes: 0,
      dependencyIds: preset.dependencyIds ?? [],
      softDependencyIds: preset.softDependencyIds ?? [],
      roadmapId: "ai-ml-main",
      roadmapTrack: preset.roadmapTrack,
      roadmapPhase: preset.roadmapPhase,
      roadmapOrder: preset.roadmapOrder,
      roadmapRoute: preset.roadmapRoute ?? inferRoadmapRouteFromTrack(preset.roadmapTrack),
      roadmapYear: preset.roadmapYear ?? inferRoadmapYearFromPhase(preset.roadmapPhase),
      roadmapStatus:
        preset.roadmapStatus ??
        normalizeRoadmapStatus(undefined, preset.scheduleMode, preset.roadmapPhase),
      scheduleMode: preset.scheduleMode,
      deadlineMode: "auto",
      scheduleCadence: preset.scheduleCadence,
      weeklyTargetBlocks: preset.weeklyTargetBlocks,
      weeklySpacingDays: preset.weeklySpacingDays,
      notes: preset.notes,
      sourceUrl: preset.sourceUrl,
      createdAt: nowIso,
      updatedAt: nowIso,
      units: preset.unitTitles.map((title, index) => ({
        id: `${preset.id}:unit-${index + 1}`,
        order: index + 1,
        title,
        estimatedMinutes: preset.estimatedMinutes,
        progressMinutes: 0,
        studySessions: [],
        actualMinutes: null,
        completed: false,
        notes: "",
      })),
    },
  ])[0];
}

export function buildRequestedLearningItems(now: Date = new Date()) {
  return learningResourcePresets.map((preset) => buildLearningItemFromPreset(preset, now));
}


